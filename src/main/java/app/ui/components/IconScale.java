package app.ui.components;

/**
 * Standard icon size scales defined in R-UI-15 (07-ui-consistency-rules.md):
 * - SM: base - 2 (badge, chevron, table cell icon, footer)
 * - MD: base (buttons, toolbar, pane header, tree cell, tab - default)
 * - LG: base + 4 (dialog header)
 * - XL: base * 2.5 (empty state)
 */
public enum IconScale {
    SM,
    MD,
    LG,
    XL
}
